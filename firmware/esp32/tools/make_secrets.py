"""Create the git-ignored secrets.h for push alerts.

Usage (from the repository root):
    python firmware/esp32/tools/make_secrets.py path/to/service-account-key.json
    python firmware/esp32/tools/make_secrets.py path/to/key.json --wifi   # bench lock only

Writes firmware/esp32/rolling_code_lock_esp32_alerts/secrets.h with the
service account (project id, client email, private key).

Wi-Fi and the alert topic are normally set per lock from the RollKey app, so
they are not needed here. --wifi additionally asks for a Wi-Fi name and
password (hidden) to pre-load a bench lock. Optional WIFI_SSID / WIFI_PASS /
FCM_TOPIC lines already in secrets.h are kept unless --wifi replaces them.
It never prints the key, the password or the topic. secrets.h is in .gitignore.
"""
import getpass
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SKETCH_SECRETS = ROOT / "firmware/esp32/rolling_code_lock_esp32_alerts/secrets.h"
OPTIONAL = ("WIFI_SSID", "WIFI_PASS", "FCM_TOPIC")


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def existing_optional() -> dict[str, str]:
    """Keep the optional #define lines (raw text) from an existing secrets.h."""
    if not SKETCH_SECRETS.exists():
        return {}
    found = {}
    for line in SKETCH_SECRETS.read_text(encoding="utf-8").splitlines():
        m = re.match(r"#define\s+(\w+)\s+(\".*\")\s*$", line)
        if m and m.group(1) in OPTIONAL:
            found[m.group(1)] = m.group(2)
    return found


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    want_wifi = "--wifi" in sys.argv[1:]
    if len(args) != 1:
        sys.exit(__doc__)
    key = json.loads(Path(args[0]).read_text(encoding="utf-8"))
    for field in ("project_id", "client_email", "private_key"):
        if not key.get(field):
            sys.exit(f"The key file has no '{field}'. Is it a service account JSON key?")
    if ")KEY\"" in key["private_key"]:
        sys.exit("Unexpected private key format.")

    optional = existing_optional()
    if want_wifi:
        optional["WIFI_SSID"] = c_string(input("Wi-Fi name (SSID, 2.4 GHz): ").strip())
        optional["WIFI_PASS"] = c_string(getpass.getpass("Wi-Fi password (hidden): "))

    text = (
        "// GENERATED by make_secrets.py. Git-ignored. Never commit, print or share.\n"
        "#pragma once\n\n"
        f"#define FCM_PROJECT_ID   {c_string(key['project_id'])}\n"
        f"#define FCM_CLIENT_EMAIL {c_string(key['client_email'])}\n\n"
        f"static const char FCM_PRIVATE_KEY[] = R\"KEY({key['private_key']})KEY\";\n"
    )
    if optional:
        text += "\n// Development only: pre-load a bench lock (see alerts.h PROVISION_FROM_SECRETS)\n"
        for name in OPTIONAL:
            if name in optional:
                text += f"#define {name:<16} {optional[name]}\n"
    SKETCH_SECRETS.write_text(text, encoding="utf-8")

    print("Wrote", SKETCH_SECRETS.relative_to(ROOT))
    print("Firebase project:", key["project_id"])
    if optional:
        print("Kept development values:", ", ".join(n for n in OPTIONAL if n in optional))


if __name__ == "__main__":
    main()
