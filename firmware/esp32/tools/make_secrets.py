"""Create the git-ignored secret files for push alerts.

Usage (from the repository root):
    python firmware/esp32/tools/make_secrets.py path/to/service-account-key.json

It asks for the Wi-Fi name and password (the password is not echoed), makes a
random alert topic (or keeps the existing one), and writes:
    firmware/esp32/rolling_code_lock_esp32_alerts/secrets.h
    app/android/secrets.properties
It never prints the key, the password or the topic. Both files are in .gitignore.
"""
import getpass
import json
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SKETCH_SECRETS = ROOT / "firmware/esp32/rolling_code_lock_esp32_alerts/secrets.h"
APP_SECRETS = ROOT / "app/android/secrets.properties"


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def existing_topic() -> str | None:
    if not APP_SECRETS.exists():
        return None
    for line in APP_SECRETS.read_text(encoding="utf-8").splitlines():
        if line.startswith("ALERT_TOPIC=") and line.split("=", 1)[1].strip():
            return line.split("=", 1)[1].strip()
    return None


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    key = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    for field in ("project_id", "client_email", "private_key"):
        if not key.get(field):
            sys.exit(f"The key file has no '{field}'. Is it a service account JSON key?")
    if ")KEY\"" in key["private_key"]:
        sys.exit("Unexpected private key format.")

    ssid = input("Wi-Fi name (SSID): ").strip()
    password = getpass.getpass("Wi-Fi password (hidden): ")
    topic = existing_topic() or "lock-alerts-" + secrets.token_hex(12)

    SKETCH_SECRETS.write_text(
        "// GENERATED by make_secrets.py. Git-ignored. Never commit, print or share.\n"
        "#pragma once\n\n"
        f"#define WIFI_SSID        {c_string(ssid)}\n"
        f"#define WIFI_PASS        {c_string(password)}\n"
        f"#define FCM_PROJECT_ID   {c_string(key['project_id'])}\n"
        f"#define FCM_CLIENT_EMAIL {c_string(key['client_email'])}\n"
        f"#define FCM_TOPIC        {c_string(topic)}\n\n"
        f"static const char FCM_PRIVATE_KEY[] = R\"KEY({key['private_key']})KEY\";\n",
        encoding="utf-8",
    )
    APP_SECRETS.write_text(
        "# GENERATED by make_secrets.py. Git-ignored. Must match FCM_TOPIC in secrets.h.\n"
        f"ALERT_TOPIC={topic}\n",
        encoding="utf-8",
    )
    print("Wrote", SKETCH_SECRETS.relative_to(ROOT))
    print("Wrote", APP_SECRETS.relative_to(ROOT))
    print("Firebase project:", key["project_id"])


if __name__ == "__main__":
    main()
